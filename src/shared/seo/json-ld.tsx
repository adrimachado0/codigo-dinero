import type { EducationalOrganization, FAQPage, Graph, WebSite } from "schema-dts";

import { site } from "@/shared/config/site";

/** Serializes JSON-LD safe for an inline <script>: `<` can't close the tag. */
export function serializeJsonLd(data: Graph): string {
  return JSON.stringify(data).replace(/</g, "\\u003c");
}

export function JsonLd({ data }: { data: Graph }) {
  return (
    <script
      type="application/ld+json"
      // Safe: serializeJsonLd escapes `<`.
      dangerouslySetInnerHTML={{ __html: serializeJsonLd(data) }}
    />
  );
}

const absolute = (path: string) => new URL(path, site.url).toString();

/** Only real profile URLs: "#" placeholders are left out until the links exist. */
const sameAs = site.social.map((s) => s.href).filter((href) => /^https?:\/\//.test(href));

/** Square emblem on the brand background (public/icons, generated by `pnpm icons`). */
const LOGO = { path: "/icons/icon-512.png", size: 512 };

/** `topics`: what the academy teaches (the topics ribbon), as `knowsAbout`. */
export function organizationLd(topics: readonly string[] = []): EducationalOrganization {
  return {
    "@type": "EducationalOrganization",
    "@id": absolute("/#organization"),
    name: site.name,
    alternateName: site.logoText,
    url: site.homeUrl,
    logo: {
      "@type": "ImageObject",
      url: absolute(LOGO.path),
      width: String(LOGO.size),
      height: String(LOGO.size),
    },
    description: site.description,
    ...(topics.length > 0 && { knowsAbout: [...topics] }),
    ...(sameAs.length > 0 && { sameAs }),
  };
}

export function websiteLd(): WebSite {
  return {
    "@type": "WebSite",
    "@id": absolute("/#website"),
    name: site.name,
    alternateName: site.logoText,
    url: site.homeUrl,
    description: site.description,
    inLanguage: "es",
    publisher: { "@id": absolute("/#organization") },
  };
}

/**
 * The home page itself, as FAQPage (a WebPage subtype), built from the same items the
 * accordion renders (single source of truth).
 */
export function faqPageLd(items: readonly { question: string; answer: string }[]): FAQPage {
  return {
    "@type": "FAQPage",
    "@id": absolute("/#faq"),
    url: site.homeUrl,
    name: site.title,
    description: site.description,
    inLanguage: "es",
    isPartOf: { "@id": absolute("/#website") },
    about: { "@id": absolute("/#organization") },
    mainEntity: items.map((item) => ({
      "@type": "Question",
      name: item.question,
      acceptedAnswer: { "@type": "Answer", text: item.answer },
    })),
  };
}

export function graph(...nodes: (EducationalOrganization | WebSite | FAQPage)[]): Graph {
  return { "@context": "https://schema.org", "@graph": nodes };
}
